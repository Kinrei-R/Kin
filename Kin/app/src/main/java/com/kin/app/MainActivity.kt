class MainActivity : ComponentActivity() {

    private val viewModel: KinViewModel by viewModels()

    // R.string.default_web_client_id is generated by the google-services plugin from google-services.json.
    private val googleClient by lazy {
        val options = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
            .requestIdToken(getString(R.string.default_web_client_id))
            .requestEmail()
            .requestProfile()
            .build()
        GoogleSignIn.getClient(this, options)
    }

    private val signInLauncher = registerForActivityResult(ActivityResultContracts.StartActivityForResult()) { result ->
        if (result.resultCode == Activity.RESULT_CANCELED && result.data == null) {
            viewModel.onSignInCancelled()
            return@registerForActivityResult
        }
        try {
            val account = GoogleSignIn.getSignedInAccountFromIntent(result.data)
                .getResult(ApiException::class.java)
            val idToken = account.idToken
            if (idToken.isNullOrEmpty()) {
                viewModel.onSignInFailed("Google did not return an ID token. Check your Firebase configuration.")
            } else {
                viewModel.signInWithGoogle(idToken)
            }
        } catch (e: ApiException) {
            if (e.statusCode == GoogleSignInStatusCodes.SIGN_IN_CANCELLED) {
                viewModel.onSignInCancelled()
            } else {
                viewModel.onSignInFailed(
                    "Google sign-in failed (${GoogleSignInStatusCodes.getStatusCodeString(e.statusCode)})"
                )
            }
        }
    }

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        enableEdgeToEdge()
        setContent {
            KinTheme {
                KinRoot(
                    viewModel = viewModel,
                    onSignInWithGoogle = {
                        viewModel.onSignInStarted()
                        // Sign out of the client first so the account chooser is always shown.
                        googleClient.signOut().addOnCompleteListener {
                            signInLauncher.launch(googleClient.signInIntent)
                        }
                    },
                    onSignOut = {
                        googleClient.signOut().addOnCompleteListener { viewModel.signOut() }
                    }
                )
            }
        }
    }
}

private fun isListenerEnabled(context: Context): Boolean =
    NotificationManagerCompat.getEnabledListenerPackages(context).contains(context.packageName)

@Composable
private fun KinRoot(viewModel: KinViewModel, onSignInWithGoogle: () -> Unit, onSignOut: () -> Unit) {
    val context = LocalContext.current
    val lifecycleOwner = LocalLifecycleOwner.current
    var enabled by remember { mutableStateOf(isListenerEnabled(context)) }

    // Re-check whenever the user returns from the system settings screen.
    DisposableEffect(lifecycleOwner) {
        val observer = LifecycleEventObserver { _, event ->
            if (event == Lifecycle.Event.ON_RESUME) enabled = isListenerEnabled(context)
        }
        lifecycleOwner.lifecycle.addObserver(observer)
        onDispose { lifecycleOwner.lifecycle.removeObserver(observer) }
    }

    if (enabled) MainNavigation(viewModel, onSignInWithGoogle, onSignOut) else PermissionScreen()
}

private enum class Tab(val route: String, val label: String, val icon: ImageVector) {
    Home("home", "Home", Icons.Filled.Home),
    Friends("friends", "Friends", Icons.Filled.Person)
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun MainNavigation(viewModel: KinViewModel, onSignInWithGoogle: () -> Unit, onSignOut: () -> Unit) {
    val session by viewModel.session.collectAsStateWithLifecycle()

    when (val s = session) {
        SessionState.Loading -> Surface(Modifier.fillMaxSize()) {
            Column(Modifier.fillMaxSize(), verticalArrangement = Arrangement.Center, horizontalAlignment = Alignment.CenterHorizontally) {
                CircularProgressIndicator()
            }
        }

        is SessionState.SignedOut -> LoginScreen(
            busy = s.busy,
            error = s.error,
            onSignInWithGoogle = onSignInWithGoogle
        )

        is SessionState.Error -> Surface(Modifier.fillMaxSize()) {
            Column(
                Modifier.fillMaxSize().padding(32.dp),
                verticalArrangement = Arrangement.spacedBy(16.dp, Alignment.CenterVertically),
                horizontalAlignment = Alignment.CenterHorizontally
            ) {
                Text("Couldn't load your profile", style = MaterialTheme.typography.titleLarge)
                Text(s.message, textAlign = TextAlign.Center, color = MaterialTheme.colorScheme.error)
                Button(onClick = viewModel::bootstrap) { Text("Retry") }
                TextButton(onClick = onSignOut) { Text("Sign out") }
            }
        }

        is SessionState.Ready -> {
            val navController = rememberNavController()
            val backStack by navController.currentBackStackEntryAsState()
            val currentRoute = backStack?.destination?.route

            Scaffold(
                topBar = {
                    CenterAlignedTopAppBar(
                        title = { Text("Kin") },
                        actions = { TextButton(onClick = onSignOut) { Text("Sign out") } }
                    )
                },
                bottomBar = {
                    NavigationBar {
                        Tab.entries.forEach { tab ->
                            NavigationBarItem(
                                selected = currentRoute == tab.route,
                                onClick = {
                                    navController.navigate(tab.route) {
                                        popUpTo(navController.graph.findStartDestination().id) { saveState = true }
                                        launchSingleTop = true
                                        restoreState = true
                                    }
                                },
                                icon = { Icon(tab.icon, contentDescription = tab.label) },
                                label = { Text(tab.label) }
                            )
                        }
                    }
                }
            ) { padding ->
                NavHost(navController, startDestination = Tab.Home.route, modifier = Modifier.padding(padding)) {
                    composable(Tab.Home.route) { HomeScreen(viewModel, s.profile) }
                    composable(Tab.Friends.route) { FriendsScreen(viewModel, s.profile) }
                }
            }
        }
    }
}
